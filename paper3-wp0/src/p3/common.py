"""Shared helpers for scripts: argument parsing, paths, report writing, batch evaluation."""
from __future__ import annotations

import argparse
import datetime as _dt
import shlex
import sys
import warnings
from pathlib import Path

import numpy as np

warnings.filterwarnings("ignore")

ROOT = Path(__file__).resolve().parents[2]
REPORTS = ROOT / "reports"
INTERIM = ROOT / "data" / "interim"
RULES_PATH = ROOT / "rules" / "rules.json"


DEFAULT_GRID = "cigre_pv_wind"
GRID = DEFAULT_GRID


def parser(desc: str) -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(description=desc)
    p.add_argument("--seed", type=int, default=7)
    p.add_argument("--grid", default=DEFAULT_GRID, help="cigre_pv_wind (WP0 reference) or sherlock")
    return p


def init(args):
    """Select the grid named by --grid; file names below get a grid suffix for non-default grids."""
    global GRID
    from . import envelope as E
    GRID = args.grid
    E.use_grid(GRID)
    return args


def suffixed(name: str) -> str:
    if GRID == DEFAULT_GRID:
        return name
    stem, dot, ext = name.rpartition(".")
    return f"{stem}_{GRID}.{ext}" if dot else f"{name}_{GRID}"


def rules_path():
    return ROOT / "rules" / suffixed("rules.json")


def bounds_path():
    return ROOT / "rules" / suffixed("model_error_bounds.json")


def interim(name: str):
    INTERIM.mkdir(parents=True, exist_ok=True)
    return INTERIM / suffixed(name)


def command_line() -> str:
    return "python " + " ".join(shlex.quote(a) for a in [str(Path(sys.argv[0]).relative_to(ROOT)) if Path(sys.argv[0]).is_absolute() else sys.argv[0], *sys.argv[1:]])


def write_report(name: str, body: str):
    REPORTS.mkdir(exist_ok=True)
    name = suffixed(name)
    head = (f"<!-- generated by `{command_line()}` on {_dt.datetime.now().isoformat(timespec='seconds')} -->\n")
    if GRID != DEFAULT_GRID:
        head += f"<!-- grid: {GRID} -->\n"
    (REPORTS / name).write_text(head + body)


def md_table(header, rows) -> str:
    out = ["| " + " | ".join(map(str, header)) + " |", "| " + " | ".join("---" for _ in header) + " |"]
    for r in rows:
        out.append("| " + " | ".join(map(str, r)) + " |")
    return "\n".join(out) + "\n"


def fmt(v, nd=4):
    if v is None:
        return "⟨·⟩"
    if isinstance(v, (bool, np.bool_)):
        return "yes" if v else "no"
    if isinstance(v, (int, np.integer)):
        return str(int(v))
    if isinstance(v, float) and not np.isfinite(v):
        return str(v)
    return f"{float(v):.{nd}f}"


def evaluate_batch(X, ci, configs):
    """Evaluate many states with the fast AC solver.
    Returns dict of arrays: conv, benign, viol, M (nan rows where not converged)."""
    from . import measure as M
    n = len(X)
    nm = len(M.names())
    out = {"conv": np.zeros(n, bool), "benign": np.zeros(n, bool), "viol": np.full(n, np.inf),
           "M": np.full((n, nm), np.nan)}
    for i, (x, c) in enumerate(zip(X, ci)):
        ok, b, v, m = M.evaluate(x, configs[c])
        out["conv"][i], out["benign"][i], out["viol"][i] = ok, b, v
        if ok:
            out["M"][i] = m
    return out
